package tse.lab.fiscalizacionautomatica.ruleengine.data;

import com.mongodb.ErrorCategory;
import com.mongodb.MongoBulkWriteException;
import com.mongodb.MongoWriteException;
import com.mongodb.bulk.BulkWriteError;
import com.mongodb.client.MongoCollection;
import com.mongodb.client.MongoDatabase;
import com.mongodb.client.model.Filters;
import com.mongodb.client.model.IndexOptions;
import com.mongodb.client.model.Indexes;
import com.mongodb.client.model.InsertManyOptions;
import com.mongodb.client.model.Sorts;
import com.mongodb.client.model.Updates;
import java.time.Clock;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Date;
import java.util.List;
import org.bson.Document;
import org.bson.conversions.Bson;
import tse.lab.fiscalizacionautomatica.ruleengine.model.TrackingEvent;

/**
 * Saves the events in the MongoDB tracking collection. The _id is generated by MongoDB; an event is
 * identified by (licensePlate, timestamp), with a unique index: a redelivered message hits it and is
 * not saved twice. Each event is saved with detected = false and marked as detected once evaluated.
 */
public class MongoTrackingEventDAO implements TrackingEventDAO {

    public static final String COLLECTION = "tracking";

    private final MongoCollection<Document> collection;
    private final Clock clock;

    public MongoTrackingEventDAO(MongoDatabase database, Clock clock) {
        this.collection = database.getCollection(COLLECTION);
        this.clock = clock;
    }

    /** Creates the indexes if they don't exist (does nothing if they do). */
    public void createIndexes() {
        collection.createIndex(Indexes.ascending("licensePlate", "timestamp"),
                new IndexOptions().unique(true).name("licensePlate_timestamp"));
        // Only the pending events are indexed: the ones the recovery looks for
        collection.createIndex(Indexes.ascending("receivedAt"),
                new IndexOptions().name("pending_receivedAt").partialFilterExpression(Filters.eq("detected", false)));
    }

    @Override
    public boolean save(TrackingEvent event) {
        try {
            collection.insertOne(toDocument(event, clock.instant()));
            return true;
        } catch (MongoWriteException e) {
            if (e.getError().getCategory() == ErrorCategory.DUPLICATE_KEY) {
                return false;
            }
            throw e;
        }
    }

    @Override
    public List<Boolean> saveAll(List<TrackingEvent> events) {
        List<Boolean> saved = new ArrayList<>(Collections.nCopies(events.size(), true));
        if (events.isEmpty()) {
            return saved;
        }
        Instant receivedAt = clock.instant();
        try {
            // Unordered: a duplicate doesn't stop the rest of the batch from being inserted
            collection.insertMany(events.stream().map(event -> toDocument(event, receivedAt)).toList(),
                    new InsertManyOptions().ordered(false));
        } catch (MongoBulkWriteException e) {
            if (e.getWriteConcernError() != null) {
                throw e;
            }
            for (BulkWriteError error : e.getWriteErrors()) {
                if (ErrorCategory.fromErrorCode(error.getCode()) != ErrorCategory.DUPLICATE_KEY) {
                    throw e;
                }
                saved.set(error.getIndex(), false);
            }
        }
        return saved;
    }

    @Override
    public List<TrackingEvent> findByLicensePlateBetween(String matricula, Instant desde, Instant hasta, int limit) {
        if (matricula == null || matricula.isBlank() || desde == null || hasta == null
                || !desde.isBefore(hasta) || limit < 1) {
            throw new IllegalArgumentException("Matrícula, rango y límite GPS inválidos");
        }
        return collection.find(Filters.and(Filters.eq("licensePlate", matricula),
                        Filters.gte("timestamp", Date.from(desde)), Filters.lt("timestamp", Date.from(hasta))))
                .sort(Sorts.ascending("timestamp"))
                .limit(limit)
                .map(MongoTrackingEventDAO::fromDocument)
                .into(new ArrayList<>());
    }

    @Override
    public void markDetected(TrackingEvent event) {
        Bson pending = Filters.and(Filters.eq("licensePlate", event.licensePlate()),
                Filters.eq("timestamp", Date.from(event.timestamp())), Filters.eq("detected", false));
        collection.updateOne(pending, Updates.combine(
                Updates.set("detected", true),
                Updates.set("detectedAt", Date.from(clock.instant()))));
    }

    @Override
    public List<TrackingEvent> findPendingDetection(Instant receivedBefore, int limit) {
        return collection.find(Filters.and(Filters.eq("detected", false), Filters.lt("receivedAt", Date.from(receivedBefore))))
                .sort(Sorts.ascending("receivedAt"))
                .limit(limit)
                .map(MongoTrackingEventDAO::fromDocument)
                .into(new ArrayList<>());
    }

    /** The location is stored as a GeoJSON point ([longitude, latitude]) to allow geospatial queries. */
    static Document toDocument(TrackingEvent event, Instant receivedAt) {
        return new Document("messageId", event.messageId())
                .append("externalId", event.externalId())
                .append("gpsId", event.gpsId())
                .append("licensePlate", event.licensePlate())
                .append("location", new Document("type", "Point")
                        .append("coordinates", List.of(event.longitude(), event.latitude())))
                .append("timestamp", Date.from(event.timestamp()))
                .append("receivedAt", Date.from(receivedAt))
                .append("detected", false);
    }

    static TrackingEvent fromDocument(Document document) {
        List<Double> coordinates = document.get("location", Document.class).getList("coordinates", Double.class);
        return new TrackingEvent(document.getString("messageId"), document.getLong("externalId"),
                document.getLong("gpsId"), document.getString("licensePlate"), coordinates.get(1), coordinates.get(0),
                document.getDate("timestamp").toInstant());
    }
}
